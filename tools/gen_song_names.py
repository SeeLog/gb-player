#!/usr/bin/env python3
"""Generate crates/gb-music/src/names.rs from pret disassemblies.

Usage: gen_song_names.py <pokered> <pokeyellow> <pokegold> <pokecrystal> > names.rs

Only song titles and IDs are extracted; no ROM data is involved.
"""
import re
import sys


def pretty(label):
    label = re.sub(r"^(Music_|MUSIC_)", "", label)
    if "_" in label or label.isupper():
        words = label.split("_")
        out = []
        for w in words:
            out.append(w if w in ("SS", "MT", "RB", "GS") else w.capitalize())
        s = " ".join(out)
    else:
        s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", " ", label)
        s = re.sub(r"(?<=[A-Za-z])(?=[0-9])", " ", s)
    return s.replace("Pokemon", "Pokémon").replace("Pkmn", "Pokémon")


def gen1(root, banks):
    songs = []
    for k in range(1, banks + 1):
        index = 0
        for f in (f"sfxheaders{k}.asm", f"musicheaders{k}.asm"):
            for line in open(f"{root}/audio/headers/{f}"):
                line = line.split(";")[0].strip()
                m = re.match(r"^(Music_\w+)::?$", line)
                if m:
                    songs.append((k, index, pretty(m.group(1))))
                elif line.startswith("db $ff, $ff, $ff"):
                    index += 1
                elif line.startswith("channel ") or line.startswith("channel\t"):
                    index += 1
    return songs


def gen2(root):
    names = []
    for line in open(f"{root}/constants/music_constants.asm"):
        m = re.match(r"^\s*const (MUSIC_\w+)", line)
        if m:
            names.append(pretty(m.group(1)))
    return names


def emit_gen1(name, songs):
    print(f"pub const {name}: &[(u8, u8, &str)] = &[")
    for bank, idx, title in songs:
        print(f'    ({bank}, 0x{idx:02X}, "{title}"),')
    print("];\n")


def emit_gen2(name, titles):
    print(f"pub const {name}: &[&str] = &[")
    for t in titles:
        print(f'    "{t}",')
    print("];\n")


red, yellow, gold, crystal = sys.argv[1:5]
print("//! Song titles taken from the pret disassemblies. Generated by tools/gen_song_names.py.\n")
print("/// (audio bank ordinal starting at 1, sound ID, title)")
emit_gen1("RED_BLUE", gen1(red, 3))
print("/// (audio bank ordinal starting at 1, sound ID, title)")
emit_gen1("YELLOW", gen1(yellow, 4))
emit_gen2("GOLD_SILVER", gen2(gold))
emit_gen2("CRYSTAL", gen2(crystal))
