#!/usr/bin/env python3
"""Generate the built-in song database (songdb/) from pret disassemblies.

Usage: gen_song_names.py <pokered> <pokeyellow> <pokegold> <pokecrystal> <songdb dir>

Writes <songdb>/pokemon-gen1/{songs,en}.toml and <songdb>/pokemon-gen2/{songs,en}.toml.
Song keys and English titles come from the pret labels; only song titles and IDs are
extracted, no ROM data is involved. Translations (ja.toml, ...) are written by hand and are
not touched. Per-song overrides added to songs.toml by hand are lost on regeneration.
"""
import os
import re
import sys


def strip(label):
    return re.sub(r"^(Music_|MUSIC_)", "", label)


def key(label):
    label = strip(label)
    if "_" in label or label.isupper():
        return label.lower()
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", label)
    s = re.sub(r"(?<=[A-Za-z])(?=[0-9])", "_", s)
    return s.lower()


def pretty(label):
    label = strip(label)
    if "_" in label or label.isupper():
        words = label.split("_")
        out = []
        for w in words:
            out.append(w if w in ("SS", "MT", "RB", "GS") else w.capitalize())
        s = " ".join(out)
    else:
        s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", " ", label)
        s = re.sub(r"(?<=[A-Za-z])(?=[0-9])", " ", s)
    return s.replace("Pokemon", "Pokémon").replace("Pkmn", "Pokémon")


def gen1(root, banks):
    """(audio bank ordinal starting at 1, sound ID, label, hidden) for every song.

    Sound effects whose first channel is a music channel (the Poké Flute plays on channel 3)
    look like songs to the player, so they are listed too, as hidden."""
    songs = []
    for k in range(1, banks + 1):
        index = 0
        label = None
        for f in (f"sfxheaders{k}.asm", f"musicheaders{k}.asm"):
            for line in open(f"{root}/audio/headers/{f}"):
                line = line.split(";")[0].strip()
                m = re.match(r"^((?:Music|SFX)_\w+)::?$", line)
                if m:
                    label = m.group(1)
                elif line.startswith("db $ff, $ff, $ff"):
                    index += 1
                elif line.startswith("channel ") or line.startswith("channel\t"):
                    if label:
                        channel = int(line.split()[1].rstrip(","))
                        if label.startswith("Music_"):
                            songs.append((k, index, label, False))
                        elif channel <= 4:
                            songs.append((k, index, label, True))
                        label = None
                    index += 1
    return songs


def gen2(root):
    """(music ID, label) for every song except MUSIC_NONE."""
    labels = []
    for line in open(f"{root}/constants/music_constants.asm"):
        m = re.match(r"^\s*const (MUSIC_\w+)", line)
        if m:
            labels.append(m.group(1))
    return [(i, label) for i, label in enumerate(labels) if i > 0]


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_series(out, series, header, games):
    """games: [(id, header titles, [(bank or None, id, label, hidden)])]"""
    os.makedirs(f"{out}/{series}", exist_ok=True)
    titles = {}
    with open(f"{out}/{series}/songs.toml", "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# {header}\n# Generated by tools/gen_song_names.py from the pret disassemblies.\n")
        for game_id, header_titles, songs in games:
            f.write(f"\n[[game]]\nid = {quote(game_id)}\n")
            f.write(f"titles = [{', '.join(quote(t) for t in header_titles)}]\n")
            f.write("songs = [\n")
            for bank, sid, label, hidden in songs:
                k = key(label)
                if not hidden:
                    titles.setdefault(k, OFFICIAL_TITLES.get(series, {}).get(k) or pretty(label))
                bank_part = f"bank = {bank}, " if bank is not None else ""
                hidden_part = ", hidden = true" if hidden else ""
                f.write(f"    {{ {bank_part}id = 0x{sid:02X}, key = {quote(k)}{hidden_part} }},\n")
            f.write("]\n")
    with open(f"{out}/{series}/en.toml", "w", encoding="utf-8", newline="\n") as f:
        if series in OFFICIAL_SOURCES:
            f.write(f"# English song titles: the official ones from {OFFICIAL_SOURCES[series]},\n")
            f.write("# the pret labels for songs it does not have.\n")
        else:
            f.write("# English song titles, from the pret labels.\n")
        f.write("\n[games]\n")
        for game_id, name in GAME_NAMES[series]:
            f.write(f"{quote(game_id)} = {quote(name)}\n")
        f.write("\n[songs]\n")
        for k, t in titles.items():
            f.write(f"{k} = {quote(t)}\n")


